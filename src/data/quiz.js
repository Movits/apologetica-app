// Escolhe quiz determinístico por dia (mesmo quiz pra todo mundo no mesmo dia).
export function getQuizOfDay(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((date - start) / (1000 * 60 * 60 * 24));
  const seed = (dayOfYear + date.getFullYear() * 13) % QUIZ.length;
  return QUIZ[seed];
}

// Escolhe N perguntas aleatórias (modo "praticar") sem repetir.
export function getRandomQuestions(n = 10) {
  const shuffled = [...QUIZ].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(n, QUIZ.length));
}

// Modo verdadeiro/falso: retorna N afirmações aleatórias.
export function getRandomTrueFalse(n = 10) {
  const shuffled = [...TRUE_FALSE].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(n, TRUE_FALSE.length));
}
